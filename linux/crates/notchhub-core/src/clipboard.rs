//! Clipboard history (text only). Skips anything the source marks as secret, such as password managers.
use serde::{Deserialize, Serialize};
use std::path::Path;

pub const MAX_ENTRIES: usize = 100;

#[derive(Clone, Debug, Serialize, Deserialize, PartialEq)]
pub struct Entry {
    pub text: String,
    #[serde(default)]
    pub pinned: bool,
    pub time: i64,
}

#[derive(Default, Serialize, Deserialize, Clone, Debug)]
pub struct History {
    pub entries: Vec<Entry>,
}

/// Marks used by password managers (KeePassXC, Bitwarden, 1Password...) and clipboard managers' own hints.
pub fn is_secret(mime_types: &[String]) -> bool {
    const HINTS: [&str; 5] = [
        "x-kde-passwordmanagerhint",
        "org.nspasteboard.concealedtype",
        "org.nspasteboard.transienttype",
        "org.nspasteboard.autogeneratedtype",
        "com.agilebits.onepassword",
    ];
    mime_types.iter().any(|m| HINTS.contains(&m.to_lowercase().as_str()))
}

impl History {
    pub fn load_from(path: &Path) -> History {
        std::fs::read_to_string(path).ok().and_then(|t| serde_json::from_str(&t).ok()).unwrap_or_default()
    }
    pub fn save_to(&self, path: &Path) {
        if let Some(d) = path.parent() {
            let _ = std::fs::create_dir_all(d);
        }
        if let Ok(t) = serde_json::to_string(self) {
            let _ = std::fs::write(path, t);
        }
    }

    /// Adds a copied text at the top (an existing identical entry moves up and keeps its pin).
    pub fn push(&mut self, text: &str, now: i64) -> bool {
        if text.trim().is_empty() {
            return false;
        }
        let pinned = self.entries.iter().find(|e| e.text == text).map_or(false, |e| e.pinned);
        self.entries.retain(|e| e.text != text);
        self.entries.insert(0, Entry { text: text.to_string(), pinned, time: now });
        // trim the oldest unpinned entries
        while self.entries.len() > MAX_ENTRIES {
            match self.entries.iter().rposition(|e| !e.pinned) {
                Some(i) => {
                    self.entries.remove(i);
                }
                None => break,
            }
        }
        true
    }
    pub fn toggle_pin(&mut self, text: &str) {
        if let Some(e) = self.entries.iter_mut().find(|e| e.text == text) {
            e.pinned = !e.pinned;
        }
    }
    pub fn remove(&mut self, text: &str) {
        self.entries.retain(|e| e.text != text);
    }
    /// Clears everything except pinned entries.
    pub fn clear(&mut self) {
        self.entries.retain(|e| e.pinned);
    }
    /// Pinned first, then by time (already newest first).
    pub fn ordered(&self) -> Vec<&Entry> {
        let mut v: Vec<&Entry> = self.entries.iter().collect();
        v.sort_by_key(|e| !e.pinned);
        v
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dedupes_and_moves_to_top_keeping_pin() {
        let mut h = History::default();
        h.push("a", 1);
        h.push("b", 2);
        h.toggle_pin("a");
        h.push("a", 3);
        assert_eq!(h.entries[0].text, "a");
        assert!(h.entries[0].pinned);
        assert_eq!(h.entries.len(), 2);
    }

    #[test]
    fn ignores_blank_and_trims_to_max_keeping_pinned() {
        let mut h = History::default();
        assert!(!h.push("   ", 0));
        h.push("keep", 0);
        h.toggle_pin("keep");
        for i in 0..150 {
            h.push(&format!("t{i}"), i);
        }
        assert_eq!(h.entries.len(), MAX_ENTRIES);
        assert!(h.entries.iter().any(|e| e.text == "keep"));
    }

    #[test]
    fn secrets_are_detected() {
        assert!(is_secret(&["text/plain".into(), "x-kde-passwordManagerHint".into()]));
        assert!(!is_secret(&["text/plain".into()]));
    }

    #[test]
    fn clear_keeps_pinned_and_pinned_show_first() {
        let mut h = History::default();
        h.push("a", 1);
        h.push("b", 2);
        h.toggle_pin("a");
        assert_eq!(h.ordered()[0].text, "a");
        h.clear();
        assert_eq!(h.entries.len(), 1);
    }
}
