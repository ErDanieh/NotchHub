import AppKit
import SwiftUI

struct ClipEntry: Identifiable, Codable, Equatable {
    var id = UUID()
    var text: String
    var copiedAt = Date()
    var pinned = false
    var source: String?
}

/// Clipboard history (text only). Skips anything apps mark as secret, such as password managers.
@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipEntry] = []
    private let fileURL: URL
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let maxUnpinned = 100
    private let secretTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
    ]

    init() {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("NotchHub", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        fileURL = dir.appendingPathComponent("clipboard.json")
        if let data = try? Data(contentsOf: fileURL), let saved = try? JSONDecoder().decode([ClipEntry].self, from: data) { items = saved }
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = pb.types ?? []
        if types.contains(where: { secretTypes.contains($0) }) { return }
        guard let text = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines), !text.isEmpty else { return }
        add(text, source: NSWorkspace.shared.frontmostApplication?.localizedName)
    }

    private func add(_ text: String, source: String?) {
        var pinned = false
        if let i = items.firstIndex(where: { $0.text == text }) { pinned = items[i].pinned; items.remove(at: i) }
        items.insert(ClipEntry(text: String(text.prefix(5000)), pinned: pinned, source: source), at: 0)
        let unpinned = items.indices.filter { !items[$0].pinned }
        if unpinned.count > maxUnpinned { items.remove(at: unpinned.last!) }
        save()
    }

    /// Put an entry back on the pasteboard without logging it as a new copy.
    func copy(_ entry: ClipEntry) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(entry.text, forType: .string)
        lastChange = pb.changeCount
        if let i = items.firstIndex(of: entry) { var e = items.remove(at: i); e.copiedAt = Date(); items.insert(e, at: 0); save() }
        NSHapticFeedbackManager.defaultPerformer.perform(.alignment, performanceTime: .default)
    }
    func togglePin(_ entry: ClipEntry) {
        if let i = items.firstIndex(of: entry) { items[i].pinned.toggle(); save() }
    }
    func remove(_ entry: ClipEntry) { items.removeAll { $0.id == entry.id }; save() }
    func clearUnpinned() { items.removeAll { !$0.pinned }; save() }

    private func save() {
        if let data = try? JSONEncoder().encode(items) { try? data.write(to: fileURL, options: .atomic) }
    }
}

struct ClipboardTab: View {
    @ObservedObject var store: ClipboardStore
    @State private var justCopied: UUID?

    var body: some View {
        VStack(spacing: Tok.Space.xs) {
            if store.items.isEmpty {
                Text("Nothing copied yet. Copy some text and it shows up here.")
                    .font(Tok.Font.sm).foregroundStyle(Tok.Color.textMuted).multilineTextAlignment(.center)
                    .frame(maxWidth: .infinity, maxHeight: .infinity)
            } else {
                ScrollView {
                    LazyVStack(spacing: Tok.Space.xxs) {
                        // pinned first, then newest
                        ForEach(store.items.sorted { ($0.pinned ? 1 : 0, $0.copiedAt) > ($1.pinned ? 1 : 0, $1.copiedAt) }) { e in
                            ClipRow(entry: e, copied: justCopied == e.id,
                                    onCopy: { store.copy(e); justCopied = e.id
                                              DispatchQueue.main.asyncAfter(deadline: .now() + 1) { if justCopied == e.id { justCopied = nil } } },
                                    onPin: { store.togglePin(e) }, onDelete: { store.remove(e) })
                        }
                    }
                }.scrollIndicators(.hidden)
                HStack {
                    Spacer()
                    Button("Clear unpinned") { store.clearUnpinned() }
                        .buttonStyle(.plain).font(Tok.Font.xs).foregroundStyle(Tok.Color.textMuted)
                }
            }
        }
        .padding(Tok.Space.sm)
        .frame(maxWidth: .infinity, maxHeight: .infinity)
        .background(Tok.Color.surface, in: RoundedRectangle(cornerRadius: Tok.Radius.lg))
    }
}

struct ClipRow: View {
    let entry: ClipEntry
    let copied: Bool
    let onCopy: () -> Void, onPin: () -> Void, onDelete: () -> Void
    @State private var hover = false

    var body: some View {
        HStack(spacing: Tok.Space.sm) {
            Button(action: onCopy) {
                VStack(alignment: .leading, spacing: 1) {
                    Text(entry.text).font(Tok.Font.sm).foregroundStyle(Tok.Color.text).lineLimit(1).truncationMode(.tail)
                    Text(copied ? "Copied" : [entry.source, entry.copiedAt.formatted(.relative(presentation: .named))]
                            .compactMap { $0 }.joined(separator: " · "))
                        .font(Tok.Font.xs).foregroundStyle(copied ? Tok.Color.success : Tok.Color.textMuted)
                }
                .frame(maxWidth: .infinity, alignment: .leading).contentShape(Rectangle())
            }.buttonStyle(.plain).accessibilityLabel("Copy: \(entry.text)")
            if hover || entry.pinned {
                Button(action: onPin) { Image(systemName: entry.pinned ? "pin.fill" : "pin")
                    .foregroundStyle(entry.pinned ? Tok.Color.neon : Tok.Color.textMuted) }
                    .buttonStyle(.plain).accessibilityLabel(entry.pinned ? "Unpin" : "Pin")
            }
            if hover {
                Button(action: onDelete) { Image(systemName: "xmark").foregroundStyle(Tok.Color.textMuted) }
                    .buttonStyle(.plain).accessibilityLabel("Delete")
            }
        }
        .padding(.horizontal, Tok.Space.sm).padding(.vertical, 3)
        .background(hover ? Tok.Color.surfaceHover : .clear, in: RoundedRectangle(cornerRadius: Tok.Radius.sm))
        .onHover { hover = $0 }
    }
}
